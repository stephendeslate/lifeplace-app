class InvoiceModelTestCase(TestCase):
    """Test cases for Invoice and InvoiceLineItem models"""

    def setUp(self):
        """Set up test data"""
        self.user = User.objects.create_user(
            email="client@test.com", first_name="Test", last_name="Client", role="CLIENT"
        )

        self.event_type = EventType.objects.create(name="Wedding")
        self.event = Event.objects.create(
            client=self.user,
            event_type=self.event_type,
            name="Test Wedding",
            start_date=date.today() + timedelta(days=30),
        )

        self.category = ProductCategory.objects.create(name="Wedding Packages")
        self.product = ProductOption.objects.create(
            name="Premium Package",
            base_price=Decimal("2500.00"),
            currency="PHP",
            category=self.category,
            type="PACKAGE",
        )

    def test_invoice_creation(self):
        """Test invoice creation"""
        invoice = Invoice.objects.create(
            event=self.event,
            client=self.user,
            total_amount=Decimal("2800.00"),
            tax_amount=Decimal("300.00"),
            subtotal=Decimal("2500.00"),
            currency="PHP",
            status="DRAFT",
            issue_date=date.today(),
            due_date=date.today() + timedelta(days=30),
        )

        self.assertEqual(invoice.total_amount, Decimal("2800.00"))
        self.assertEqual(invoice.currency, "PHP")
        self.assertEqual(invoice.status, "DRAFT")
        self.assertIsNotNone(invoice.invoice_id)

    def test_invoice_line_item_creation(self):
        """Test invoice line item creation and total calculation"""
        invoice = Invoice.objects.create(
            event=self.event,
            client=self.user,
            total_amount=Decimal("0.00"),
            tax_amount=Decimal("0.00"),
            subtotal=Decimal("0.00"),
            currency="PHP",
            issue_date=date.today(),
            due_date=date.today() + timedelta(days=30),
        )

        line_item = InvoiceLineItem.objects.create(
            invoice=invoice,
            product=self.product,
            description="Premium Wedding Package",
            quantity=1,
            unit_price=Decimal("2500.00"),
            total=Decimal("2500.00"),
            tax_rate=Decimal("12.00"),
        )

        self.assertEqual(line_item.total, Decimal("2500.00"))

    def test_invoice_status_transitions(self):
        """Test invoice status transitions"""
        invoice = Invoice.objects.create(
            event=self.event,
            client=self.user,
            total_amount=Decimal("2800.00"),
            tax_amount=Decimal("300.00"),
            subtotal=Decimal("2500.00"),
            currency="PHP",
            status="DRAFT",
            issue_date=date.today(),
            due_date=date.today() + timedelta(days=30),
        )

        # DRAFT -> ISSUED
        invoice.status = "ISSUED"
        invoice.save()
        self.assertEqual(invoice.status, "ISSUED")

        # ISSUED -> PAID
        invoice.status = "PAID"
        invoice.save()
        self.assertEqual(invoice.status, "PAID")

    def test_invoice_paid_amount_property(self):
        """Test invoice paid_amount computed property"""
        invoice = Invoice.objects.create(
            event=self.event,
            client=self.user,
            total_amount=Decimal("2500.00"),
            tax_amount=Decimal("300.00"),
            subtotal=Decimal("2200.00"),
            currency="PHP",
            status="ISSUED",
            issue_date=date.today(),
            due_date=date.today() + timedelta(days=30),
        )

        # No payments yet
        self.assertEqual(invoice.paid_amount, Decimal("0.00"))
        self.assertFalse(invoice.is_fully_paid)


class PaymentTransactionModelTestCase(TestCase):
    """Test cases for PaymentTransaction model"""

    def setUp(self):
        """Set up test data"""
        self.user = User.objects.create_user(
            email="test@example.com", first_name="Test", last_name="User", role="CLIENT"
        )

        self.event_type = EventType.objects.create(name="Wedding")
        self.event = Event.objects.create(
            client=self.user,
            event_type=self.event_type,
            name="Test Wedding",
            start_date=date.today() + timedelta(days=30),
        )

        self.gateway, _ = PaymentGateway.objects.get_or_create(
            code="stripe",
            defaults={
                "name": "Stripe Test",
                "is_active": True,
            },
        )
        self.gateway.is_active = True
        self.gateway.save()

        self.payment_method = PaymentMethod.objects.create(
            gateway=self.gateway, user=self.user, token_reference="test_token_123"
        )

        self.payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("2500.00"),
            currency="PHP",
            due_date=date.today() + timedelta(days=7),
        )

    def test_transaction_creation(self):
        """Test payment transaction creation"""
        txn = PaymentTransaction.objects.create(
            payment=self.payment,
            gateway=self.gateway,
            transaction_id="pi_test_123456",
            status="COMPLETED",
            amount=Decimal("2500.00"),
            currency="PHP",
            response_data={"status": "succeeded", "id": "pi_test_123456"},
        )

        self.assertEqual(txn.transaction_id, "pi_test_123456")
        self.assertEqual(txn.status, "COMPLETED")
        self.assertEqual(txn.amount, Decimal("2500.00"))
        self.assertIn("status", txn.response_data)

    def test_failed_transaction(self):
        """Test failed transaction handling"""
        txn = PaymentTransaction.objects.create(
            payment=self.payment,
            gateway=self.gateway,
            transaction_id="pi_test_failed",
            status="FAILED",
            amount=Decimal("2500.00"),
            currency="PHP",
            error_message="Your card was declined.",
            response_data={"error": {"code": "card_declined"}},
        )

        self.assertEqual(txn.status, "FAILED")
        self.assertIsNotNone(txn.error_message)

    def test_refund_transaction(self):
        """Test that multiple transactions can be created for same payment"""
        # First create a successful charge
        PaymentTransaction.objects.create(
            payment=self.payment,
            gateway=self.gateway,
            transaction_id="pi_test_123456",
            status="COMPLETED",
            amount=Decimal("2500.00"),
            currency="PHP",
        )

        # Then create a refund transaction (separate record)
        refund_txn = PaymentTransaction.objects.create(
            payment=self.payment,
            gateway=self.gateway,
            transaction_id="re_test_123456",
            status="COMPLETED",
            amount=Decimal("2500.00"),
            currency="PHP",
        )

        self.assertEqual(refund_txn.transaction_id, "re_test_123456")
        self.assertEqual(refund_txn.amount, Decimal("2500.00"))

        # Both transactions should exist for this payment
        self.assertEqual(PaymentTransaction.objects.filter(payment=self.payment).count(), 2)
