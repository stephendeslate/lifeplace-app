class PaymentModelTestCase(TestCase):
    """Test cases for Payment model"""

    def setUp(self):
        """Set up test data"""
        self.user = User.objects.create_user(
            email="test@example.com", first_name="Test", last_name="User", role="CLIENT"
        )

        self.event_type = EventType.objects.create(name="Wedding", description="Wedding events")

        self.event = Event.objects.create(
            client=self.user,
            event_type=self.event_type,
            name="Test Wedding",
            start_date=date.today() + timedelta(days=30),
            status="CONFIRMED",
        )

        self.gateway, _ = PaymentGateway.objects.get_or_create(
            code="stripe",
            defaults={
                "name": "Stripe Test",
                "is_active": True,
            },
        )
        # Always update config to ensure test settings are applied
        self.gateway.config = {"test_mode": True}
        self.gateway.is_active = True
        self.gateway.save()

        self.payment_method = PaymentMethod.objects.create(
            gateway=self.gateway, user=self.user, token_reference="test_token_123", last_four="4242", is_default=True
        )

    def test_payment_creation(self):
        """Test basic payment creation"""
        payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("2500.00"),
            currency="PHP",
            status="PENDING",
            due_date=date.today() + timedelta(days=7),
        )

        self.assertEqual(payment.amount, Decimal("2500.00"))
        self.assertEqual(payment.currency, "PHP")
        self.assertEqual(payment.status, "PENDING")
        self.assertIsNotNone(payment.payment_number)
        # Payment numbers are generated by PaymentNumberService
        self.assertTrue(len(payment.payment_number) > 0)

    def test_payment_number_generation(self):
        """Test automatic payment number generation"""
        payment1 = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("1000.00"),
            currency="PHP",
            due_date=date.today() + timedelta(days=7),
        )

        payment2 = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("1500.00"),
            currency="PHP",
            due_date=date.today() + timedelta(days=7),
        )

        self.assertNotEqual(payment1.payment_number, payment2.payment_number)
        self.assertTrue(len(payment1.payment_number) > 0)
        self.assertTrue(len(payment2.payment_number) > 0)

    def test_php_currency_formatting(self):
        """Test PHP currency formatting via format_amount_with_currency"""
        payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("2500.00"),
            currency="PHP",
            due_date=date.today() + timedelta(days=7),
        )

        formatted = payment.format_amount_with_currency()
        # Should contain the peso symbol and 2,500
        self.assertIn("2,500", formatted)

    def test_usd_currency_formatting(self):
        """Test USD currency formatting via format_amount_with_currency.

        CurrencySettings defaults decimal_places=0 (PHP business context),
        so USD amounts are formatted without decimals unless CurrencySettings
        is explicitly configured with decimal_places=2.
        """
        payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("2500.50"),
            currency="USD",
            due_date=date.today() + timedelta(days=7),
        )

        formatted = payment.format_amount_with_currency()
        # With default CurrencySettings (decimal_places=0), USD amounts
        # are formatted without decimals: "$2,500" or "$2,501"
        self.assertIn("$", formatted)
        self.assertIn("2,50", formatted)  # At least contains 2,50x

    def test_payment_status_transitions(self):
        """Test valid payment status transitions"""
        payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("1000.00"),
            currency="PHP",
            status="PENDING",
            due_date=date.today() + timedelta(days=7),
        )

        # Valid transition: PENDING -> COMPLETED
        payment.status = "COMPLETED"
        payment.save()
        self.assertEqual(payment.status, "COMPLETED")

    def test_payment_state_machine_methods(self):
        """Test payment state machine integration methods"""
        payment = Payment.objects.create(
            event=self.event,
            payment_method=self.payment_method,
            amount=Decimal("2500.00"),
            currency="PHP",
            status="CREATED",
            due_date=date.today() + timedelta(days=7),
        )

        # Test can_transition_to
        self.assertTrue(payment.can_transition_to("PENDING"))

        # Test get_valid_transitions
        valid = payment.get_valid_transitions()
        self.assertIsInstance(valid, list)

        # Test is_terminal_state
        self.assertFalse(payment.is_terminal_state())


